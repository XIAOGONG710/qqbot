// 「她自己的话」实验开关（用户 2026-11-20：「感觉上像是没有自己的情绪和事情，只有我找她的被动」）。
// 提示词里有一层层「别主动说」：念头「接不上就别硬说」、状态「没人问就别主动说你累了」、心境「不用主动讲 / 不主动提 / 不用解释自己的状态」、
// 答问题「不另起话题」。每条当初都有来由（ADR 0036 机械追加进度、ADR 0101 / 0102），叠起来她只剩回应。
// 开着时这几处换成「你有自己的事和情绪，想说就说，不用等他问」的说法，别的不动。
// 只给模拟器 A/B 用（`npm run sim -- … --own-voice`）；线上不读这个开关，关着时每一句都和原来逐字一样。
// 要不要上线、怎么上线，看对比结果，先问她本人再由用户定。

let on = false;

/** 模拟器用：这一批要不要用「她自己的话」的说法 */
export function useOwnVoice(value: boolean): void {
    on = value;
}

export const ownVoice = (): boolean => on;
